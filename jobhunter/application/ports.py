"""Ports: everything the use cases need from the outside world, as Protocols.
Infrastructure provides the adapters; the container wires them together.

Records crossing these ports are plain dicts shaped like the database rows (see the migration)."""
from __future__ import annotations

from collections.abc import Callable, Iterator
from typing import Any, Protocol

Record = dict[str, Any]


# ================================================================ external services

class LLM(Protocol):
    fast_model: str
    strong_model: str

    def embed(self, texts: list[str], purpose: str = "embed") -> list[list[float]]: ...

    def structured(self, model: str, system: str, user: str, schema: dict, name: str,
                   purpose: str | None = None) -> dict: ...


UsageSink = Callable[[str, str, int, int], None]  # purpose, model, input_tokens, output_tokens
LLMFactory = Callable[[UsageSink | None], LLM]


class Storage(Protocol):
    def upload(self, path: str, data: bytes | str, content_type: str) -> str: ...

    def download(self, path: str) -> bytes: ...

    def signed_url(self, path: str, expires_in: int = 300, download_name: str | None = None) -> str | None: ...


class JobSources(Protocol):
    company_sources: tuple[str, ...]
    aggregators: tuple[str, ...]

    def collect(self, companies: dict[str, list[str]], queries: list[str], aggregators: list[str],
                keep: Callable[[Record], bool], on_source: Callable[[str], None] | None = None
                ) -> Iterator[tuple[Record | None, str | None]]:
        """Yields (job, None) for jobs where keep(job) is true, or (None, error) per failing source."""

    def fetch_posting(self, url: str) -> Record | None:
        """A single posting via its ATS API, if `url` is an ATS job URL."""

    def detect(self, url: str) -> tuple[str, str] | None:
        """(source, token) for a careers URL, looking inside the page for embedded boards."""


class WebPages(Protocol):
    def job_posting(self, url: str) -> tuple[Record | None, str]:
        """(job from JSON-LD JobPosting or None, readable page text)."""

    def site_text(self, domain: str, paths: tuple[str, ...] = ("", "/about"), limit: int = 6000) -> str: ...

    def site_emails(self, domain: str) -> list[str]: ...

    def domain_exists(self, domain: str) -> bool: ...


class EmailFinder(Protocol):
    enabled: bool

    def search(self, domain: str | None, company: str | None) -> list[Record]:
        """[{email, name, role, confidence}]"""


class Mailer(Protocol):
    def configured(self) -> bool: ...

    def auth_url(self, state: str) -> str: ...

    def exchange_code(self, code: str, state: str) -> tuple[dict, str]:
        """-> (token, account email)"""

    def send(self, token: dict, sender: str, to: str, subject: str, body: str,
             attachment: tuple[str, bytes, str] | None, on_token: Callable[[dict], None]) -> tuple[str, str]:
        """-> (message_id, thread_id)"""

    def thread_messages(self, token: dict, thread_id: str, on_token: Callable[[dict], None]) -> list[Record]:
        """[{from, internal_ms, snippet}]"""


class Notifier(Protocol):
    def desktop(self, title: str, body: str) -> None: ...


class DocumentRenderer(Protocol):
    def cv_html(self, context: dict) -> str: ...

    def pdf(self, html: str) -> bytes | None: ...


class TextExtractor(Protocol):
    supported: tuple[str, ...]

    def extract(self, filename: str, data: bytes) -> str: ...


class Scheduler(Protocol):
    def reschedule(self) -> None: ...

    def next_run(self) -> str | None: ...


# ================================================================ repositories

class JobRepo(Protocol):
    def insert_if_new(self, job: Record, fingerprint: str) -> int | None: ...
    def find_by_key_or_fingerprint(self, key: str, fingerprint: str) -> Record | None: ...
    def get(self, job_id: int) -> Record | None: ...
    def update(self, job_id: int, **fields) -> Record: ...
    def list(self, *, stage=None, min_fit=None, source=None, q=None, feedback=None, since=None,
             sort="fit", limit=50, offset=0) -> tuple[list[Record], int]: ...
    def sources(self) -> list[Record]: ...
    def needing_embedding(self, job_ids: list[int] | None = None, limit: int = 500) -> list[Record]: ...
    def set_embedding(self, job_id: int, embedding: list[float]) -> None: ...
    def similarity_candidates(self, job_ids: list[int]) -> list[Record]: ...
    def to_score(self, limit: int, job_ids: list[int] | None = None) -> list[Record]: ...
    def top_scored(self, min_fit: int, limit: int) -> list[int]: ...
    def feedback_examples(self, limit: int = 10) -> list[Record]: ...
    def counts(self, job_id: int) -> Record: ...
    def stage_counts(self) -> dict[str, int]: ...
    def board(self, stages: tuple[str, ...]) -> list[Record]: ...
    def skill_counts(self, field: str, min_fit: int, limit: int) -> list[Record]: ...
    def count_fit_at_least(self, min_fit: int) -> int: ...
    def dashboard(self) -> Record: ...


class UserRepo(Protocol):
    def get(self, user_id: str | None = None) -> Record | None: ...
    def ensure(self, user_id: str, email: str) -> Record: ...
    def update(self, user_id: str, **fields) -> Record: ...


class CVRepo(Protocol):
    def list(self) -> list[Record]: ...
    def get(self, cv_id: int) -> Record | None: ...
    def default(self) -> Record | None: ...
    def any(self) -> bool: ...
    def create(self, **fields) -> Record: ...
    def update(self, cv_id: int, **fields) -> Record: ...
    def delete(self, cv_id: int) -> None: ...
    def set_default(self, cv_id: int) -> None: ...
    def clear_embedding(self, cv_id: int) -> None: ...
    def missing_embeddings(self) -> list[Record]: ...
    def set_embedding(self, cv_id: int, embedding: list[float]) -> None: ...
    def any_embedded(self) -> bool: ...


class SettingsRepo(Protocol):
    def get(self) -> Record: ...
    def update(self, **fields) -> Record: ...


class CompanyRepo(Protocol):
    def list(self) -> list[Record]: ...
    def by_source(self, active_only: bool = True) -> dict[str, list[str]]: ...
    def upsert(self, source: str, token: str, name: str | None, domain: str | None) -> Record: ...
    def update(self, company_id: int, **fields) -> Record | None: ...
    def delete(self, company_id: int) -> None: ...
    def domain_for(self, company: str) -> str | None: ...


class ApplicationRepo(Protocol):
    def get(self, app_id: int) -> Record | None: ...
    def for_job(self, job_id: int) -> list[Record]: ...
    def latest(self, job_id: int) -> Record | None: ...
    def next_version(self, job_id: int) -> int: ...
    def create(self, **fields) -> Record: ...


class ContactRepo(Protocol):
    def for_job(self, job_id: int) -> list[Record]: ...
    def get(self, contact_id: int) -> Record | None: ...
    def upsert(self, job_id: int, domain: str | None, c: Record) -> bool: ...
    def add_manual(self, job_id: int, domain: str | None, email: str, name: str | None, role: str | None) -> Record: ...
    def delete(self, contact_id: int) -> None: ...


class OutreachRepo(Protocol):
    def get(self, outreach_id: int) -> Record | None: ...
    def for_job(self, job_id: int) -> list[Record]: ...
    def create(self, **fields) -> Record: ...
    def update(self, outreach_id: int, **fields) -> Record: ...
    def delete(self, outreach_id: int) -> None: ...
    def awaiting_reply(self) -> list[Record]: ...
    def recent_replies(self, limit: int = 5) -> list[Record]: ...


class EventRepo(Protocol):
    def add(self, job_id: int, kind: str, note: str | None = None) -> Record: ...
    def for_job(self, job_id: int) -> list[Record]: ...
    def recent(self, limit: int = 12) -> list[Record]: ...


class ReminderRepo(Protocol):
    def list(self, include_done: bool = False) -> list[Record]: ...
    def next_for_job(self, job_id: int) -> Record | None: ...
    def create(self, **fields) -> Record: ...
    def update(self, reminder_id: int, **fields) -> Record | None: ...
    def delete(self, reminder_id: int) -> None: ...
    def has_open_auto(self, job_id: int) -> bool: ...
    def close_auto(self, job_id: int) -> None: ...
    def due_unnotified(self) -> list[Record]: ...
    def mark_notified(self, reminder_id: int) -> None: ...


class PrepRepo(Protocol):
    def create(self, job_id: int, content: dict) -> Record: ...
    def latest(self, job_id: int) -> Record | None: ...


class NotificationRepo(Protocol):
    def create(self, kind: str, title: str, body: str, job_id: int | None) -> Record: ...
    def list(self, unread: bool, limit: int) -> list[Record]: ...
    def unread_count(self) -> int: ...
    def mark_read(self, ids: list[int] | None) -> None: ...


class IntegrationRepo(Protocol):
    def get(self, provider: str) -> Record | None: ...
    def set_pending_state(self, provider: str, state: str) -> None: ...
    def save_token(self, provider: str, token: dict | None, email: str | None) -> None: ...
    def update_token(self, provider: str, token: dict) -> None: ...


class RunRepo(Protocol):
    def active_of_kind(self, kind: str) -> Record | None: ...
    def create(self, kind: str, params: dict, trigger: str) -> Record: ...
    def update(self, run_id: int, **fields) -> Record: ...
    def append_log(self, run_id: int, line: str) -> None: ...
    def get(self, run_id: int) -> Record | None: ...
    def list(self, limit: int, kind: str | None = None) -> list[Record]: ...
    def active(self) -> list[Record]: ...
    def mark_interrupted(self) -> None: ...


class UsageRepo(Protocol):
    def record(self, run_id: int | None, purpose: str, model: str, tin: int, tout: int, cost: float) -> None: ...
    def spent_since(self, start) -> float: ...
    def run_cost(self, run_id: int) -> float: ...
    def report(self, start, end) -> Record: ...


class Repositories(Protocol):
    """One bundle per connection (unit of work)."""
    jobs: JobRepo
    users: UserRepo
    cvs: CVRepo
    settings: SettingsRepo
    companies: CompanyRepo
    applications: ApplicationRepo
    contacts: ContactRepo
    outreach: OutreachRepo
    events: EventRepo
    reminders: ReminderRepo
    prep: PrepRepo
    notifications: NotificationRepo
    integrations: IntegrationRepo
    runs: RunRepo
    usage: UsageRepo

    def transaction(self): ...
